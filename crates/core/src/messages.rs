//! Built-in installer messages (wording follows Inno Setup's translations).
//! Placeholders: `[name]`, `[name/ver]`, `[mb]`, `%1`, `%2`.

pub const LANGS: &[(&str, &str)] = &[("en", "English"), ("ru", "Русский"), ("uk", "Українська")];

pub fn normalize_lang(id: &str) -> &'static str {
    match id.trim().to_ascii_lowercase().as_str() {
        "ru" | "rus" | "russian" | "русский" => "ru",
        "uk" | "ua" | "ukr" | "ukrainian" | "українська" => "uk",
        _ => "en",
    }
}

pub fn lang_name(id: &str) -> &'static str {
    let n = normalize_lang(id);
    LANGS.iter().find(|l| l.0 == n).map(|l| l.1).unwrap_or("English")
}

/// Windows primary language id -> our id.
pub fn lang_from_langid(langid: u16) -> &'static str {
    match langid & 0x3ff {
        0x19 => "ru",
        0x22 => "uk",
        _ => "en",
    }
}

