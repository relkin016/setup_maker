fn table(lang: &str) -> Table {
    match normalize_lang(lang) {
        "ru" => RU,
        "uk" => UK,
        _ => EN,
    }
}

/// Built-in message, falling back to English, then to the key itself.
pub fn builtin(lang: &str, key: &str) -> Option<&'static str> {
    let find = |t: Table| t.iter().find(|(k, _)| k.eq_ignore_ascii_case(key)).map(|(_, v)| *v);
    find(table(lang)).or_else(|| find(EN))
}

/// Substitute `%1..%9` with args.
pub fn fmt(s: &str, args: &[&str]) -> String {
    let mut out = String::with_capacity(s.len() + 16);
    let mut it = s.chars().peekable();
    while let Some(c) = it.next() {
        if c == '%' {
            if let Some(d) = it.peek().and_then(|d| d.to_digit(10)) {
                it.next();
                if d >= 1 && (d as usize) <= args.len() {
                    out.push_str(args[d as usize - 1]);
                }
                continue;
            }
            if it.peek() == Some(&'n') {
                it.next();
                out.push('\n');
                continue;
            }
        }
        out.push(c);
    }
    out
}
